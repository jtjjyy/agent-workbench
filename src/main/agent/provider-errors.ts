import { RUN_ERROR_MESSAGES } from '../../shared/zh-CN';

export const PROVIDER_ERRORS = {
  API_KEY_REQUIRED: RUN_ERROR_MESSAGES.API_KEY_REQUIRED,
  DATA_EGRESS_NOT_APPROVED: RUN_ERROR_MESSAGES.DATA_EGRESS_NOT_APPROVED,
  SECURE_STORAGE_UNAVAILABLE: RUN_ERROR_MESSAGES.SECURE_STORAGE_UNAVAILABLE,
  SETTINGS_READ_FAILED: RUN_ERROR_MESSAGES.SETTINGS_READ_FAILED,
  PROVIDER_AUTH_FAILED: RUN_ERROR_MESSAGES.PROVIDER_AUTH_FAILED,
  PROVIDER_BALANCE_REQUIRED: RUN_ERROR_MESSAGES.PROVIDER_BALANCE_REQUIRED,
  PROVIDER_RATE_LIMITED: RUN_ERROR_MESSAGES.PROVIDER_RATE_LIMITED,
  PROVIDER_REQUEST_REJECTED: RUN_ERROR_MESSAGES.PROVIDER_REQUEST_REJECTED,
  PROVIDER_UNAVAILABLE: RUN_ERROR_MESSAGES.PROVIDER_UNAVAILABLE,
  PROVIDER_FAILED: RUN_ERROR_MESSAGES.PROVIDER_FAILED,
  PROVIDER_INCOMPLETE: RUN_ERROR_MESSAGES.PROVIDER_INCOMPLETE,
  OUTPUT_LIMIT_REACHED: RUN_ERROR_MESSAGES.OUTPUT_LIMIT_REACHED,
  RUN_BUDGET_EXCEEDED: RUN_ERROR_MESSAGES.RUN_BUDGET_EXCEEDED,
  WORKSPACE_UNAVAILABLE: RUN_ERROR_MESSAGES.WORKSPACE_UNAVAILABLE,
  FILE_EDIT_UNCONFIRMED: RUN_ERROR_MESSAGES.FILE_EDIT_UNCONFIRMED,
} as const;

export type ProviderErrorCode = keyof typeof PROVIDER_ERRORS;

export class ProviderError extends Error {
  constructor(readonly code: ProviderErrorCode) {
    super(PROVIDER_ERRORS[code]);
    this.name = 'ProviderError';
  }
}

export function providerStatusCode(status: number | undefined): ProviderErrorCode {
  if (status === 401 || status === 403) return 'PROVIDER_AUTH_FAILED';
  if (status === 402) return 'PROVIDER_BALANCE_REQUIRED';
  if (status === 429) return 'PROVIDER_RATE_LIMITED';
  if (status === 400 || status === 404 || status === 422) return 'PROVIDER_REQUEST_REJECTED';
  if (status !== undefined && status >= 500) return 'PROVIDER_UNAVAILABLE';
  return 'PROVIDER_FAILED';
}
